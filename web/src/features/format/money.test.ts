import { describe, expect, it } from 'vitest';
import { formatWon } from './money.ts';

describe('formatWon', () => {
  it.each([
    ['0', '0원'],
    ['999', '999원'],
    ['1000', '1,000원'],
    ['62300000', '62,300,000원'],
    ['62300000.0000', '62,300,000원'],
    ['-1234.5000', '-1,235원'],
    ['1234.4999', '1,234원'],
    ['123456789012.5', '123,456,789,013원'],
    ['100000000', '100,000,000원'],
    ['999.5', '1,000원'],
    ['0.5', '1원'],
    ['-0.5', '-1원'],
    ['0.004', '0원'],
    ['-0.004', '0원'],
    ['0.000000001', '0원'],
    ['123456789012345678901.9', '123,456,789,012,345,678,902원'],
  ])('formats %s as %s', (input, expected) => {
    expect(formatWon(input)).toBe(expected);
  });

  it.each(['abc', '', '1e5', '1,000', ' 5', '-', '1.', 'NaN'])(
    'returns %j unchanged',
    (input) => {
      expect(formatWon(input)).toBe(input);
    },
  );
});
